const u8 *font5x7_glyph(char c) {
    unsigned uc = (unsigned char)c;
    if (uc < 0x20 || uc > 0x7E) return FONT[0]; /* blank */
    return FONT[uc - 0x20];
}

i32 text_width(const char *s, i32 scale, i32 spacing) {
    if (!s || scale < 1) return 0;
    /* Return the width of the WIDEST line: draw_impl resets the pen on '\n', so
     * a multi-line string's drawn extent is the longest single line, not the
     * sum of all glyphs. Track the per-line glyph count and keep the max. */
    i32 maxn = 0, n = 0;
    for (const char *p = s; *p; ++p) {
        if (*p == '\n') { if (n > maxn) maxn = n; n = 0; }
        else n++;
    }
    if (n > maxn) maxn = n;
    if (maxn == 0) return 0;
    /* maxn glyphs, (maxn-1) inter-glyph gaps */
    return (maxn * FONT_W + (maxn - 1) * spacing) * scale;
}

void text_char(Framebuffer *fb, i32 x, i32 y, char c, Color3 col,
               i32 scale, int additive) {
    if (scale < 1) scale = 1;
    const u8 *g = font5x7_glyph(c);
    for (i32 ry = 0; ry < FONT_H; ++ry) {
        u8 rowbits = g[ry];
        for (i32 rx = 0; rx < FONT_W; ++rx) {
            if (!(rowbits & (1u << (FONT_W - 1 - rx)))) continue;
            i32 px0 = x + rx * scale, py0 = y + ry * scale;
            for (i32 sy = 0; sy < scale; ++sy)
                for (i32 sx = 0; sx < scale; ++sx) {
                    if (additive) fb_add(fb, px0 + sx, py0 + sy, col);
                    else          fb_set(fb, px0 + sx, py0 + sy, col);
                }
        }
    }
}

static void draw_impl(Framebuffer *fb, i32 x, i32 y, const char *s, Color3 col,
                      i32 scale, i32 spacing, int additive) {
    if (!s) return;
    if (scale < 1) scale = 1;
    i32 pen_x = x, pen_y = y;
    const i32 adv = (FONT_W + spacing) * scale;
    const i32 line = (FONT_H + 1) * scale;
    for (const char *p = s; *p; ++p) {
        if (*p == '\n') { pen_x = x; pen_y += line; continue; }
        text_char(fb, pen_x, pen_y, *p, col, scale, additive);
        pen_x += adv;
    }
}

void text_draw(Framebuffer *fb, i32 x, i32 y, const char *s, Color3 col,
               i32 scale, i32 spacing) {
    draw_impl(fb, x, y, s, col, scale, spacing, 0);
}
void text_draw_add(Framebuffer *fb, i32 x, i32 y, const char *s, Color3 col,
                   i32 scale, i32 spacing) {
    draw_impl(fb, x, y, s, col, scale, spacing, 1);
}
